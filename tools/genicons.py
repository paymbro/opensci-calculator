# Generate app/src/core/icons.js: 4-level bitmaps (' ' white, '.' light gray, '+' dark gray, '#' black)
# cut from the official manual screenshots.
import sys, json
import numpy as np
from PIL import Image
base, out = sys.argv[1], sys.argv[2]

def lv(v):
    return '#' if v <= 42 else '+' if v <= 127 else '.' if v <= 212 else ' '

def crop_native(name, x, y, w, h):
    a = np.array(Image.open(f'{base}/native/{name}.png'))
    return [''.join(lv(v) for v in a[yy, x:x + w]) for yy in range(y, y + h)]

def crop2x(fname, w, h):
    a = np.array(Image.open(f'{base}/screens/{fname}').convert('L'))
    return [''.join(lv(a[2 * yy, 2 * xx]) for xx in range(w)) for yy in range(h)]

icons = {
    'mathI': crop_native('p027_10', 25, 2, 14, 7),
    'angleD': crop_native('p027_10', 43, 2, 6, 7),
    'angleR': crop_native('p035_0', 51, 2, 6, 7),
    'FIX': crop_native('p027_4', 69, 2, 11, 7),
    'SCI': crop_native('p027_10', 83, 2, 11, 7),
    'cplxI': crop_native('p103_11', 107, 2, 4, 7),
    'cplxPolar': crop_native('p113_27', 113, 2, 7, 7),
    'down': crop_native('p043_11', 150, 2, 7, 7),
    'up': crop_native('p027_10', 158, 2, 7, 7),
}
apps = ['p022_4', 'p022_5', 'p022_6', 'p023_0', 'p023_1', 'p023_2', 'p023_3', 'p023_4', 'p023_5', 'p023_6',
        'p023_7', 'p024_0', 'p024_1']
names = ['Calculate', 'Statistics', 'Table', 'Equation', 'Inequality', 'Distribution', 'Complex', 'Matrix',
         'Vector', 'Spreadsheet', 'Ratio', 'MathBox', 'BaseN']
for n, a in zip(names, apps):
    icons['app_' + n] = crop2x(a + '_120x64.png', 59, 31)
lines = ['// Generated by tools/genicons.py from the official fx-991CW+ UK manual screenshots.',
         "// Levels: ' ' white, '.' light gray, '+' dark gray, '#' black.",
         'export const ICONS = {']
for k, v in icons.items():
    lines.append(f'  {k}: ' + json.dumps(v) + ',')
lines.append('};')
open(out, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
for k in ('angleD', 'angleR', 'mathI', 'app_Ratio'):
    print(k); print('\n'.join('|' + r + '|' for r in icons[k]))
