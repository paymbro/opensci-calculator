def cell(t, i, shift_x=0, shift_y=0):
    rows = [r.replace('+', '#').replace('.', ' ') for r in cells[t][i]['rows']]
    return shifted(rows, shift_x, shift_y)


def shifted(rows, dx, dy):
    H, W = len(rows), len(rows[0])
    o = []
    for y in range(H):
        s = ''
        for x in range(W):
            sx, sy = x - dx, y - dy
            s += rows[sy][sx] if 0 <= sy < H and 0 <= sx < W else ' '
        o.append(s)
    return o


