def sup(rows, x=0, top=0):
    g = [' ' * 11 for _ in range(14)]
    for i, r in enumerate(rows):
        line = list(g[top + i])
        for j, ch in enumerate(r):
            if ch == '#': line[x + j] = '#'
        g[top + i] = ''.join(line)
    return g
